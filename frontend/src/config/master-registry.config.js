function withSection(section, entry) {
  return { ...entry, sectionId: section.id, sectionLabel: section.label };
}

export const ALL_MASTER_ITEMS = MASTER_SECTIONS.flatMap((s) =>
  s.items.filter((entry) => !entry.hidden).map((entry) => withSection(s, entry)),
);

export const ALL_MASTER_ITEMS_INCLUDING_HIDDEN = MASTER_SECTIONS.flatMap((s) =>
  s.items.map((entry) => withSection(s, entry)),
);

export function searchMasterItems(query) {
  const q = String(query || '').trim().toLowerCase();
  if (!q) return ALL_MASTER_ITEMS;
  const tokens = q.split(/\s+/).filter(Boolean);

  return ALL_MASTER_ITEMS.filter((entry) => {
    const haystack = [
      entry.label,
      entry.description,
      entry.sectionLabel,
      entry.sectionId,
      entry.id,
      entry.entity,
      entry.type,
      MASTER_TYPES[entry.type]?.label,
      ...(entry.usedIn || []),
      ...(entry.keywords || []),
      ...(entry.aliasOf ? [entry.aliasOf] : []),
    ]
      .filter(Boolean)
      .join(' ')
      .toLowerCase();
    return tokens.every((token) => haystack.includes(token));
  });
}

export const COMMUNICATION_CHANNEL_BY_SLUG = {
  'email-template': 'EMAIL',
  'sms-template': 'SMS',
  'email-automation': 'EMAIL',
  announcements: 'ANNOUNCEMENT',
};

export function getMasterBySlug(slug) {
  if (!slug) return null;
  const key = String(slug).toLowerCase();
  const exactId = ALL_MASTER_ITEMS_INCLUDING_HIDDEN.find((m) => String(m.id).toLowerCase() === key);
  if (exactId) return exactId;
  return ALL_MASTER_ITEMS_INCLUDING_HIDDEN.find((m) => {
    const routePath = String(m.route || '').split('?')[0];
    const routeSlug = routePath.split('/').pop()?.toLowerCase();
    return routeSlug === key || routePath === `/admin/master/${slug}`;
  }) || null;
}

export function getMasterHubItem(slug) {
  return getMasterBySlug(slug);
}

export function resolveMasterPage(slug) {
  const hubItem = getMasterBySlug(slug);
  if (!hubItem) return null;
  if (!hubItem.engine) {
    return { hubItem, entityConfig: null, engineEntity: null };
  }
  const engineEntity = hubItem.entity || hubItem.id;
  const entityConfig = getMasterEntityConfig(engineEntity);
  return { hubItem, entityConfig, engineEntity };
}

export function buildMasterBreadcrumbs(hubItem, extraLabel) {
  const crumbs = [
    { label: 'Admin', path: ROUTES.DASHBOARD },
    { label: 'Masters', path: ROUTES.MASTER },
  ];
  if (hubItem?.sectionId) {
    crumbs.push({
      label: hubItem.sectionLabel,
      path: `${ROUTES.MASTER}#master-${hubItem.sectionId}`,
    });
  }
  crumbs.push({ label: extraLabel || hubItem?.label || 'Master' });
  return crumbs;
}

