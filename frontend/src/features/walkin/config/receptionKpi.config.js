import {
  FiUserPlus, FiClock, FiUsers, FiCheckCircle, FiTrendingUp,
  FiActivity, FiBarChart2,
} from 'react-icons/fi';

export function buildReceptionKpiItems(metrics = {}, summary = {}) {
  const {
    todayCount = 0,
    waitingCount = 0,
    inCounsellingCount = 0,
    completedCount = 0,
    convertedCount = 0,
    avgWaitMins = 0,
    avgCounsellingMins = 0,
    conversionRate = 0,
  } = metrics;

  return [
    {
      key: 'todayWalkIns',
      label: "Today's Walk-ins",
      value: todayCount,
      trend: '+12%',
      trendUp: true,
      tone: 'primary',
      icon: FiUserPlus,
      filterValue: 'today',
      spark: [3, 5, 4, 8, 6, todayCount || 2, todayCount],
    },
    {
      key: 'waiting',
      label: 'Waiting Visitors',
      value: waitingCount,
      trend: waitingCount > 3 ? 'High' : 'Normal',
      trendUp: waitingCount <= 3,
      tone: 'warning',
      icon: FiClock,
      filterValue: 'WAITING',
      spark: [2, 4, 3, waitingCount, waitingCount, waitingCount, waitingCount],
    },
    {
      key: 'inCounselling',
      label: 'In Counselling',
      value: inCounsellingCount,
      trend: 'Live',
      trendUp: true,
      tone: 'info',
      icon: FiUsers,
      filterValue: 'IN_COUNSELLING',
      spark: [1, 2, 1, 3, inCounsellingCount, inCounsellingCount, inCounsellingCount],
    },
    {
      key: 'completed',
      label: 'Completed Today',
      value: completedCount,
      trend: '+5%',
      trendUp: true,
      tone: 'success',
      icon: FiCheckCircle,
      filterValue: 'COMPLETED',
      spark: [1, 2, 3, 4, completedCount, completedCount, completedCount],
    },
    {
      key: 'converted',
      label: 'Converted to Enquiry',
      value: convertedCount ?? summary.convertedToday ?? 0,
      trend: `${conversionRate}%`,
      trendUp: conversionRate >= 20,
      tone: 'primary',
      icon: FiTrendingUp,
      filterValue: null,
      spark: [0, 1, 1, 2, convertedCount, convertedCount, convertedCount],
    },
    {
      key: 'avgWait',
      label: 'Avg Waiting Time',
      value: `${avgWaitMins}m`,
      trend: avgWaitMins <= 15 ? 'Good' : 'Slow',
      trendUp: avgWaitMins <= 15,
      tone: 'warning',
      icon: FiActivity,
      filterValue: null,
      spark: [10, 12, 8, 15, avgWaitMins, avgWaitMins, avgWaitMins],
      isText: true,
    },
    {
      key: 'avgCounselling',
      label: 'Avg Counselling Time',
      value: `${avgCounsellingMins}m`,
      trend: 'Est.',
      trendUp: true,
      tone: 'info',
      icon: FiBarChart2,
      filterValue: null,
      spark: [20, 18, 22, avgCounsellingMins, avgCounsellingMins, avgCounsellingMins, avgCounsellingMins],
      isText: true,
    },
    {
      key: 'conversionRate',
      label: 'Walk-in Conversion',
      value: `${conversionRate}%`,
      trend: conversionRate >= 25 ? 'Strong' : 'Building',
      trendUp: conversionRate >= 25,
      tone: 'success',
      icon: FiTrendingUp,
      filterValue: null,
      spark: [10, 15, 18, conversionRate, conversionRate, conversionRate, conversionRate],
      isText: true,
    },
  ];
}
